export type MqttSubtopic = 'telemetry' | 'status' | 'cmd' | 'ack';

export interface MqttTopicParams {
  tenantId: string;
  farmId: string;
  greenhouseId: string;
  deviceId: string;
}

/**
 * Builds standard WormWise hierarchical MQTT topic
 * Format: wormwise/{tenantId}/{farmId}/{greenhouseId}/{deviceId}/{subtopic}
 */
export function buildMqttTopic(params: MqttTopicParams, subtopic: MqttSubtopic): string {
  return `wormwise/${params.tenantId}/${params.farmId}/${params.greenhouseId}/${params.deviceId}/${subtopic}`;
}

/**
 * Parses a WormWise MQTT topic into its components
 */
export function parseMqttTopic(topic: string): {
  params: MqttTopicParams;
  subtopic: MqttSubtopic;
} | null {
  const parts = topic.split('/');
  if (parts.length !== 6 || parts[0] !== 'wormwise') {
    return null;
  }
  return {
    params: {
      tenantId: parts[1],
      farmId: parts[2],
      greenhouseId: parts[3],
      deviceId: parts[4],
    },
    subtopic: parts[5] as MqttSubtopic,
  };
}

// ----------------------------------------------------------------------------
// 1. Telemetry Payload (Published by ESP32 at interval, e.g. every 10s)
// ----------------------------------------------------------------------------
export interface TelemetryPayload {
  deviceId: string;
  timestamp: string; // ISO 8601 UTC
  messageId: string; // Unique sequence or UUID
  readings: {
    soilMoisture: number; // Percentage (0-100%)
    soilTemp: number; // Celsius (°C)
    airTemp: number; // Celsius (°C)
    airHumidity: number; // Percentage (0-100%)
    co2Ppm?: number; // Optional CO2 concentration in ppm
  };
  metricsMetadata?: {
    probeId?: string;
    samplingDurationMs?: number;
  };
  batteryVoltage?: number; // Volts (e.g. 4.12V)
  wifiRssi: number; // Signal strength in dBm (-30 to -90)
}

// ----------------------------------------------------------------------------
// 2. Status / LWT Payload (Retained message, updated on boot & LWT on drop)
// ----------------------------------------------------------------------------
export interface DeviceStatusPayload {
  deviceId: string;
  timestamp: string;
  status: 'online' | 'offline';
  reason: 'boot' | 'heartbeat' | 'lwt' | 'graceful_shutdown' | 'ota_update';
  firmwareVersion: string;
  ipAddress: string;
  macAddress: string;
  freeHeapBytes: number;
  uptimeSeconds: number;
  reconnectCount: number;
}

// ----------------------------------------------------------------------------
// 3. Command Payload (Published by Backend Command Service to ESP32)
// ----------------------------------------------------------------------------
export type TargetActuator = 'misting_pump' | 'exhaust_fan' | 'drainage_pump' | 'intake_fan';

export type CommandAction = 'turn_on' | 'turn_off' | 'pulse';

export interface DeviceCommandPayload {
  commandId: string; // UUIDv4 generated by web backend
  deviceId: string; // Target ESP32 ID
  targetActuator: TargetActuator;
  action: CommandAction;
  durationSeconds?: number; // e.g. run misting pump for 30s
  createdAt: string; // ISO 8601 UTC
  expiresAt: string; // ISO 8601 UTC (ESP32 will discard if now > expiresAt)
}

// ----------------------------------------------------------------------------
// 4. Acknowledgement Payload (Published by ESP32 in response to Command)
// ----------------------------------------------------------------------------
export type AckStatus =
  | 'acknowledged' // Received and passed validation
  | 'executing' // Actuator energized
  | 'completed' // Duration elapsed or action finalized
  | 'rejected' // Safety rule or validation failure
  | 'expired'; // Arrived after expiresAt timestamp

export interface DeviceAckPayload {
  commandId: string;
  deviceId: string;
  targetActuator: TargetActuator;
  status: AckStatus;
  reason: string; // e.g. "OK", "ANTI_DROWNING_LIMIT_REACHED", "COMMAND_EXPIRED", "MALFORMED"
  actuatorState: 'running' | 'stopped';
  timestamp: string;
}
